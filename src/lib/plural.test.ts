import { describe, expect, it } from "vitest";
import { plural } from "./plural";

const days: [string, string, string] = ["день", "дня", "дней"];

describe("plural (Russian)", () => {
  it.each([
    [0, "дней"], [1, "день"], [2, "дня"], [3, "дня"], [4, "дня"], [5, "дней"], [9, "дней"],
    [10, "дней"], [11, "дней"], [12, "дней"], [13, "дней"], [14, "дней"], [15, "дней"], [19, "дней"],
    [20, "дней"], [21, "день"], [22, "дня"], [24, "дня"], [25, "дней"],
    [100, "дней"], [101, "день"], [102, "дня"], [111, "дней"], [112, "дней"], [114, "дней"], [121, "день"],
    [1000, "дней"], [1011, "дней"], [1001, "день"],
  ])("%i -> %s", (n, expected) => {
    expect(plural(n, days)).toBe(expected);
  });
});
